//! 一个具有因果关系的教学案例：先有故障日志，再根据配置生成新日志。
//! 严格只创建新的练习目录；simulate 只重写这一案例自己保留的 current.log。
use crate::simulation::{self, MINI_APP};
use std::fs::{self, OpenOptions};
use std::io::Write;
use std::path::Path;

const MARKER_V1: &str = "RustAppLab-LabQuest-Case-v1\n";
const MARKER_V2: &str = "RustAppLab-LabQuest-Case-v2\n";

/// 保留旧案例兼容：v1 只有单配置运行验证；v2 增加迁移测试。
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum CaseVersion {
    Legacy,
    Transfer,
}

pub fn version(root: &Path) -> Result<CaseVersion, String> {
    let marker = root.join(".labquest-case");
    let metadata = fs::symlink_metadata(&marker)
        .map_err(|err| format!("无法读取案例标识 {}：{err}", marker.display()))?;
    if !metadata.is_file() || metadata.file_type().is_symlink() {
        return Err("案例标识不是普通文件，拒绝操作".into());
    }
    match fs::read_to_string(&marker).as_deref() {
        Ok(MARKER_V1) => Ok(CaseVersion::Legacy),
        Ok(MARKER_V2) => Ok(CaseVersion::Transfer),
        _ => Err("案例标识不匹配，拒绝操作".into()),
    }
}

pub fn ensure_case(root: &Path) -> Result<(), String> {
    if fs::symlink_metadata(root)
        .map_err(|err| format!("无法访问案例目录 {}：{err}", root.display()))?
        .file_type()
        .is_symlink()
    {
        return Err("案例根目录不能是符号链接".into());
    }
    version(root)?;
    // write operations must remain in the original case. Refuse redirected folders.
    for relative in [
        "project",
        "project/src",
        "project/config",
        "logs",
        "deliverables",
        "backups",
        "build",
    ] {
        let dir = root.join(relative);
        let metadata =
            fs::symlink_metadata(&dir).map_err(|err| format!("案例结构缺少 {relative}：{err}"))?;
        if !metadata.is_dir() || metadata.file_type().is_symlink() {
            return Err(format!("案例目录 {relative} 不是普通目录，拒绝操作"));
        }
    }
    Ok(())
}

/// 只覆盖 LabQuest 所管理的文件，拒绝链接、目录与其他特殊目标。
/// 调用前仍必须由 ensure_case 校验案例目录及其所有父目录。
pub fn write_owned(path: &Path, content: &str) -> Result<(), String> {
    match fs::symlink_metadata(path) {
        Ok(metadata) if !metadata.is_file() || metadata.file_type().is_symlink() => {
            return Err(format!("拒绝覆盖非普通文件：{}", path.display()));
        }
        Err(err) if err.kind() != std::io::ErrorKind::NotFound => {
            return Err(format!("检查 {} 失败：{err}", path.display()));
        }
        _ => {}
    }
    fs::write(path, content).map_err(|err| format!("写入 {} 失败：{err}", path.display()))
}

fn write_new(path: &Path, content: &str) -> Result<(), String> {
    let mut file = OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(path)
        .map_err(|err| format!("创建 {} 失败：{err}", path.display()))?;
    file.write_all(content.as_bytes())
        .map_err(|err| format!("写入 {} 失败：{err}", path.display()))
}

pub fn start(root: &Path) -> Result<(), String> {
    fs::create_dir(root).map_err(|err| {
        format!(
            "创建新案例目录 {} 失败（拒绝覆盖已有路径）：{err}",
            root.display()
        )
    })?;
    for folder in [
        "project/src",
        "project/config",
        "logs",
        "deliverables",
        "backups",
        "build",
    ] {
        fs::create_dir_all(root.join(folder))
            .map_err(|err| format!("创建案例子目录失败：{err}"))?;
    }
    write_new(&root.join(".labquest-case"), MARKER_V2)?;
    write_new(&root.join("project/Cargo.toml"), "[package]\nname = \"case-gateway\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n[workspace]\n")?;
    write_new(&root.join("project/src/main.rs"), MINI_APP)?;
    write_new(&root.join("project/Cargo.lock"), "# This file is automatically @generated by Cargo.\nversion = 3\n\n[[package]]\nname = \"case-gateway\"\nversion = \"0.1.0\"\n")?;
    write_new(
        &root.join("project/config/service.conf"),
        "# 模拟网关的超时配置，单位为毫秒\ntimeout_ms=150\n",
    )?;
    write_new(&root.join("project/README.md"), "# Case Gateway\n\n这是可单独编译运行的 Rust 小程序（标准库，无外部 crates）。\n\n它读取 config/service.conf 并输出 12 条确定性模拟请求日志。\n\n**你需要亲手修改 `src/main.rs`**：统计 ERROR 记录，并在第 13 行输出 `SUMMARY requests=12 errors=N`（N 是实际错误数）。这是案例的代码关卡。

验收会在不改动你的配置文件的前提下，通过 `--timeout-ms` 用多个阈值运行**同一份 Rust 代码**。因此不能把错误数写死。你可先直接运行 `cargo run --manifest-path <案例目录>/project/Cargo.toml -- --timeout-ms 400` 观察行为。\n\n从 Rust AppLab 根目录运行：\n\n`cargo run -p labquest -- test-app <案例目录>`（从 RustAppLab 根目录运行）\n\n尖括号只是路径占位符；请替换成真实目录。LabQuest 将构建缓存放在案例根目录的 build/，避免污染 project/ 备份。\n")?;
    write_new(
        &root.join("logs/baseline.log"),
        &simulation::render_log(simulation::HEALTHY_TIMEOUT),
    )?;
    write_new(
        &root.join("logs/incident.log"),
        &simulation::render_log(simulation::INCIDENT_TIMEOUT),
    )?;
    write_new(
        &root.join("BRIEFING.md"),
        r#"# CASE 01 · 网关响应超时事故（教学模拟）

**情境**：一个本地网关在配置变更后出现大量 ERROR。你是值班工程师，需要交付“可验证的事故调查包”。

- `project/` 是你可以实际修改、编译的最小 Rust 应用。
- `logs/baseline.log` 是变更前的模拟日志；`logs/incident.log` 是事故发生时的模拟日志。
- `project/config/service.conf` 是当前的配置。`labquest simulate` 会据此生成 `logs/current.log`。
- `deliverables/` 存放文件地图、日志分析报告、Rust 程序运行证据和最终调查报告；`backups/` 存放可验证的备份。
- `build/` 只保存练习程序的编译缓存，不作为交付作品或备份内容。

## 工具箱

FileQuest 负责识别代码和配置；LogLens 负责分析并比较日志；SafeSync 负责留下经校验的快照。
LocalHub 是可选的浏览器观察站，不参与自动计分：它可以展示本案例的文件和某一份日志。

## 调查规则

1. 事故日志与健康基线不可篡改；修改它们会使案例验收失败。
2. 可以修改 `project/config/service.conf`，然后重新执行 `labquest simulate`。
3. 你必须编辑 `project/src/main.rs`，添加一行动态的 `SUMMARY requests=12 errors=N`；执行 `labquest test-app` 编译并运行代码，形成与当前源码绑定的证据。
4. `labquest status` 直接检查真实产出：报告是否与当前文件/日志相符，代码运行证据与源码/配置是否一致，备份是否完整；不是仅检查文件名。
5. 本案所有请求时延均为人工构造，故障原因和改善只针对这个确定性模拟，不能推断真实服务可靠性。
6. 不要把故障注入或破坏性实验用于个人文件。

六步验收通过后执行 `labquest finish <案例目录>`，生成可离线交付的 `deliverables/CASE_REPORT.md`。
"#,
    )?;
    Ok(())
}

/// `simulate` 有意允许重复运行，但只覆盖当前案例的 current.log，绝不写到外部路径。
pub fn simulate(root: &Path) -> Result<(u32, usize), String> {
    ensure_case(root)?;
    let timeout = simulation::read_timeout(&root.join("project"))?;
    let path = root.join("logs/current.log");
    let text = simulation::render_log(timeout);
    write_owned(&path, &text)?;
    Ok((timeout, text.matches(" ERROR ").count()))
}
